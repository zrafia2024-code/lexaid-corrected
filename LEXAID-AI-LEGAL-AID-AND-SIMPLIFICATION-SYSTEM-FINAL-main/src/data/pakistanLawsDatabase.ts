// Helper to search Pakistan Laws Database
export function searchPakistanLaws(query: string, category: string = ""): LegalArticle[] {
  const q = (query || "").trim().toLowerCase();
  const cat = (category || "").trim().toLowerCase();

  return PAKISTAN_LAWS_DATABASE.filter((item) => {
    if (cat && cat !== "all" && item.category !== cat) {
      return false;
    }
    if (!q) return true;

    const inEn =
      item.articleNumber.toLowerCase().includes(q) ||
      item.titleEn.toLowerCase().includes(q) ||
      item.summaryEn.toLowerCase().includes(q) ||
      item.citation.toLowerCase().includes(q) ||
      item.keywords.some((k) => k.toLowerCase().includes(q));

    const inUr =
      item.titleUr.includes(q) ||
      item.summaryUr.includes(q) ||
      item.partUr.includes(q) ||
      item.keywords.some((k) => k.includes(q));

    return inEn || inUr;
  });
}
